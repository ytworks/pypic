"""Tables for design/setup.md: the upstream states of the planner (plan.py), from dry plans (no GPU).

Run: .venv/bin/python research/topics/shock-alfvenic-turbulence/design/setup.py > .../design/setup-tables.md

Every number comes from ``plan.plan_topic``; times in 1 / Omega_ci, lengths in d_i. The |B|^2 spread is
std / mean over y of 1 + dB_x^2 + dB_z^2 with the linear phases of the cold two-fluid waves (plasma frame).
"""
from __future__ import annotations

import glob
import math
import os
import sys

import yaml

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

from plan import TopicParams, params_from_dict, plan_topic  # noqa: E402

TIMES = (10.0, 20.0, 40.0)


def row(label: str, **kw) -> str:
    out = []
    for t in TIMES:
        _, _, info = plan_topic(TopicParams(t_end=t, **kw))
        out.append(info["b2_spread"]["t_end"])
    n = len(info["modes"])
    return (f"| {kw.get('ly', 50.0):g} | {label} | {n} | {info['modes'][-1]['k_di']:.3f} | "
            f"{info['b2_spread']['t0']:.3f} | " + " | ".join(f"{s:.3f}" for s in out)
            + f" | {info['xi_pp']:.1f} | {info['Xi']:.1f} |")


def main():
    print("# Tables of the set-up (generated by `design/setup.py`)\n")
    print("Fixed unless stated: m_i/m_e = 100, omega_pe/Omega_ce = 10, beta_e = beta_i = 1, M_A = 4.5, "
          "rms dB_x/B0 = 0.6, helicity R, realization 0.\n")

    print("## 1. Upstream states: uniformity of |B| and field-line excursion\n")
    print("| L_y | state | modes | largest k d_i | spread t=0 | t=10 | t=20 | t=40 | xi_pp | Xi |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    for ly in (50.0, 100.0, 200.0, 400.0):
        print(row("one wave (zeros 0)", ly=ly))
    for ly, zeros, rad, kmax in ((50.0, 1, 0.3, 1.0), (50.0, 1, 0.6, 1.0), (50.0, 1, 0.3, 0.5),
                                 (100.0, 1, 0.3, 0.5), (100.0, 2, 0.6, 0.5), (200.0, 1, 0.3, 0.5),
                                 (200.0, 2, 0.6, 0.5), (400.0, 2, 0.6, 0.5)):
        print(row(f"constant_b, zeros {zeros}, radius {rad:g}, kdi_max {kmax:g}", ly=ly, zeros=zeros,
                  zero_radius=rad, kdi_max=kmax))
    for ly in (50.0, 200.0):
        for real in (0, 1, 2):
            print(row(f"random phases, realization {real}", ly=ly, state="random", realization=real))
    print()

    print("## 2. The piston and the inflow face\n")
    print("Speeds of the uniform state (B0 only). `flow`: the plasma that entered through the face reaches the shock; "
          "`fast`: a fast-mode signal from the face does.\n")
    print("| L_x | L_y | omega_pe/Omega_ce | V0 / v_A | r | V_sh / v_A | M_A (B0) | M_A (rms B) | flow | fast | "
          "Debye / dx | steps | particles |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for lx, ly, ww in ((100.0, 50.0, 10.0), (200.0, 50.0, 10.0), (200.0, 400.0, 10.0), (200.0, 50.0, 4.0)):
        cfg, _, i = plan_topic(TopicParams(lx=lx, ly=ly, wpe_wce=ww))
        s = i["shock"]
        print(f"| {lx:g} | {ly:g} | {ww:g} | {i['v0'] / i['v_a']:.3f} | {s['compression']:.3f} | "
              f"{s['v_shock'] / i['v_a']:.3f} | {s['mach_alfven']:.2f} | {s['mach_alfven'] / i['b_total']:.2f} | "
              f"{i['t_face']['flow']:.1f} | {i['t_face']['fast']:.1f} | {i['debye_cells']:.2f} | {cfg.n_steps} | "
              f"{i['particles']:.2e} |")
    print()

    print("## 3. One circular wave at the front: local field and local inflow, over the whole circle of phases\n")
    db = 0.6
    bp = math.sqrt(2.0) * db
    cfg, _, i = plan_topic(TopicParams(ly=50.0, db=db))
    ui = cfg.injection.fluctuation["modes"][0]["u"]["i"]["cos"][0] / i["v_a"]  # ion dv_x / v_A where B_x = +b B0
    u1 = (i["v0"] + i["shock"]["v_shock"]) / i["v_a"]
    bt = math.sqrt(1.0 + bp * bp)
    print(f"B / B0 = (b cos phi, 1, s b sin phi) with b = sqrt(2) x {db:g} = {bp:.3f} and phi = k y - omega t; "
          f"|B| / B0 = {bt:.3f} for every phase phi. The ion bulk velocity of the wave is dv = {ui:.3f} v_A "
          "(cos phi, 0, s sin phi) at L_y = 50 d_i (helicity R, s = 1): the wave travels along +B0. theta_Bn: angle "
          "between B and the shock normal +x. psi: angle of the projection of B on the front plane (y, z) from y. "
          "Normal inflow: speed of the ions towards a front that moves at the shock speed of the uniform state, "
          f"U1 - dv_x with U1 = {u1:.2f} v_A; the last column divides it by the Alfvén speed on |B|.\n")
    print("| phi [deg] | B_x / B0 | B_z / B0 | theta_Bn [deg] | acute theta_Bn [deg] | psi [deg] | dv_x / v_A | "
          "normal inflow / v_A | normal inflow / v_A(|B|) |")
    print("|---|---|---|---|---|---|---|---|---|")
    for phi in range(0, 360, 45):
        c, s = math.cos(math.radians(phi)), math.sin(math.radians(phi))
        theta = math.degrees(math.acos(bp * c / bt))
        psi = math.degrees(math.atan2(bp * s, 1.0))
        print(f"| {phi} | {bp * c:+.3f} | {bp * s:+.3f} | {theta:.1f} | {min(theta, 180.0 - theta):.1f} | {psi:+.1f} | "
              f"{ui * c:+.3f} | {u1 - ui * c:.3f} | {(u1 - ui * c) / bt:.3f} |")
    print()

    print("## 4. How the wave meets the front: lengths and times\n")
    print("One circular wave, rms dB_x/B0 = 0.6, helicity R. xi_pp = sqrt(2) db L_y / pi: peak-to-peak excursion of a "
          "field line along x. Connected: xi_pp / U1, the time between the first touch of a field line's arc and "
          "the passage of its last point through a plane front. Period: 2 pi / omega, the time in which the phase at "
          "a fixed point y of the front goes once around the circle. Transit: (L_y / 2) / v_te with v_te = "
          "sqrt(T_e / m_e), the thermal time between the two intersections.\n")
    print("| L_y | k d_i | omega / Omega_ci | v_ph / v_A | ion dv / v_A | electron dv / v_A | xi_pp | Xi | connected | "
          "period | transit |")
    print("|---|---|---|---|---|---|---|---|---|---|---|")
    for ly in (50.0, 100.0, 200.0, 400.0):
        cfg, _, i = plan_topic(TopicParams(ly=ly, db=db))
        m, f = i["modes"][0], cfg.injection.fluctuation["modes"][0]
        v_te = math.sqrt(i["theta_e"]) / i["v_a"]
        w = m["omega_over_omega_ci"]
        print(f"| {ly:g} | {m['k_di']:.4f} | {w:.4f} | {w / m['k_di']:.3f} | "
              f"{f['u']['i']['cos'][0] / i['v_a']:+.3f} | {f['u']['e']['cos'][0] / i['v_a']:+.3f} | {i['xi_pp']:.1f} | "
              f"{i['Xi']:.1f} | {i['xi_pp'] / u1:.1f} | {2.0 * math.pi / w:.0f} | "
              f"{0.5 * ly / v_te:.1f} |")
    print()

    print("## 5. Pilot P1a: the configurations `configs/p1a-*.yaml`\n")
    print("Periodic boxes without a shock, one GPU each. Minutes: particles x steps at 1.4e9 particle-steps per second "
          "and GPU (measured on `blast_wave/full`, notebook 2026-11-13).\n")
    print("| config | omega_pe/Omega_ce | state | rms dB_x/B0 | modes | Xi | spread t=0 | spread t_end | Debye / dx | "
          "particles | steps | t_end | minutes |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    here = os.path.dirname(os.path.abspath(__file__))
    for path in sorted(glob.glob(os.path.join(here, "..", "configs", "p1a-*.yaml"))):
        with open(path) as fh:
            d = yaml.safe_load(fh)
        p = params_from_dict(d)
        cfg, _, i = plan_topic(p)
        state = "laminar" if p.db == 0.0 else (f"{p.state}, zeros {p.zeros}" if p.state == "constant_b" else p.state)
        print(f"| `{os.path.basename(path)[:-5]}` | {p.wpe_wce:g} | {state}, {p.helicity} | {p.db:g} | "
              f"{len(i['modes']) if p.db else 0} | {i['Xi']:.2f} | {i['b2_spread']['t0']:.3f} | "
              f"{i['b2_spread']['t_end']:.3f} | {i['debye_cells']:.2f} | {i['particles']:.1e} | {cfg.n_steps} | "
              f"{p.t_end:g} | {i['particles'] * cfg.n_steps / 1.4e9 / 60.0:.0f} |")

if __name__ == "__main__":
    main()
